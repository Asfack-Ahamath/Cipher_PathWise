/* Regenerates packages/core/src/datasetExtra.ts from the official dataset folder.
   Usage: node scripts/bundle-datasets.mjs "<path to Tech-Triathlon 2026 - Datasets/data>"
   Bundles only compact, derived tables (traffic factors, road disruptions for 2026,
   the calendar, weekly demand totals, and the Task 2B peak-day scenario) so the app
   runs without the raw CSVs. Keep the repository private: these are competition data. */
import fs from 'node:fs';
import path from 'node:path';

const root = process.argv[2];
if (!root) { console.error('Pass the dataset "data" folder.'); process.exit(1); }
const find = name => { for (const d of ['General Data', 'Training Data', 'Test Data', '.']) { const p = path.join(root, d, name); if (fs.existsSync(p)) return p; } throw new Error(`missing ${name}`); };
const csv = name => {
  const [head, ...rows] = fs.readFileSync(find(name), 'utf8').trim().split(/\r?\n/);
  const keys = head.split(',');
  return rows.map(r => { const c = r.split(','); return Object.fromEntries(keys.map((k, i) => [k, c[i] ?? ''])); });
};

const cal = csv('calendar.csv');
const weekOf = new Map(cal.map(r => [r.date, `${r.iso_year}-${String(r.iso_week).padStart(2, '0')}`]));

const traffic = {};
for (const r of csv('traffic_speed.csv')) traffic[`${r.district}|${r.hour}|${r.monsoon}`] = Number(r.speed_index);

const roads = {};
for (const r of csv('road_conditions.csv')) if (r.date >= '2026-01-01' && Number(r.disruption_index) < 100) roads[`${r.district}|${r.date}`] = Number(r.disruption_index);

const calendar = cal.map(r => [r.date, Number(r.is_operating), Number(r.is_payday), r.festival || '', Number(r.festival_ramp), Number(r.is_holiday), Number(r.monsoon), Number(r.iso_year), Number(r.iso_week)]);

const weekly = {};
for (const f of ['deliveries_train.csv', 'task1_test_inputs.csv']) for (const r of csv(f)) {
  const wk = weekOf.get(r.order_date); if (!wk) continue;
  const k = `${r.depot}|${r.brand}|${wk}`;
  const w = weekly[k] ??= [0, 0, 0];
  const m3 = Number(r.order_volume_m3);
  w[0] += m3; if (r.temp_requirement === 'chilled') w[1] += m3; w[2] += 1;
}
const weeklyRows = Object.entries(weekly).map(([k, [t, c, n]]) => [k, Math.round(t * 10) / 10, Math.round(c * 10) / 10, n]).sort((a, b) => a[0].localeCompare(b[0]));

const horizon = csv('task2a_test_inputs.csv').map(r => [r.row_id, r.depot, r.brand, Number(r.iso_year), Number(r.iso_week)]);

const peak = csv('task2b_peak_day_scenarios.csv').map(r => [r.order_ref, r.outlet_id, r.temp_requirement, Number(r.order_units), Number(r.order_weight_kg), Number(r.order_volume_m3), Number(r.deferred_yesterday), Number(r.days_since_last_served)]);
const fleet = csv('task2b_peak_day_fleet.csv').map(r => [r.vehicle_id, r.status]);

const out = `/* Generated by scripts/bundle-datasets.mjs from the competition datasets — do not edit by hand.
   Compact, derived tables so PathWise runs without the raw CSV files. Competition data: keep the repository private. */

/** traffic_speed.csv: speed index (100 = free flow) by \`district|hour|monsoon\`. */
export const TRAFFIC_SPEED: Record<string, number> = ${JSON.stringify(traffic)};

/** road_conditions.csv, 2026 only, disruption index below 100 (100 = clear) by \`district|date\`. */
export const ROAD_DISRUPTION: Record<string, number> = ${JSON.stringify(roads)};

/** calendar.csv: [date, is_operating, is_payday, festival, festival_ramp, is_holiday, monsoon, iso_year, iso_week]. */
export const CALENDAR_ROWS: [string, number, number, string, number, number, number, number, number][] = ${JSON.stringify(calendar)};

/** Weekly order volume from deliveries_train.csv + task1_test_inputs.csv, by the week the store requested:
 *  [\`depot|brand|isoYear-isoWeek\`, total m³, chilled m³, orders]. */
export const WEEKLY_DEMAND: [string, number, number, number][] = ${JSON.stringify(weeklyRows)};

/** task2a_test_inputs.csv: the forecast horizon [row_id, depot, brand, iso_year, iso_week]. */
export const FORECAST_HORIZON: [string, string, string, number, number][] = ${JSON.stringify(horizon)};

/** task2b_peak_day_scenarios.csv (S1): [order_ref, outlet, temp, units, kg, m³, deferred_yesterday, days_since_last_served]. */
export const PEAK_DAY_ORDERS: [string, string, 'chilled' | 'ambient', number, number, number, number, number][] = ${JSON.stringify(peak)};

/** task2b_peak_day_fleet.csv (S1): vehicles listed with their status; unlisted vehicles are not available. */
export const PEAK_DAY_FLEET: [string, 'available' | 'in_workshop'][] = ${JSON.stringify(fleet)};
`;
const dest = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../packages/core/src/datasetExtra.ts');
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}: traffic ${Object.keys(traffic).length}, roads ${Object.keys(roads).length}, calendar ${calendar.length}, weekly ${weeklyRows.length}, horizon ${horizon.length}, peak ${peak.length}, fleet ${fleet.length}, ${Math.round(out.length / 1024)} KB`);
